        <h1 class="text-4xl">Syarat &amp; Ketentuan</h1>
        <p class="text-sm text-stone-500">Berlaku sejak 2 November 2026</p>

        <p>Dengan menggunakan Hadist Apa, kamu menyetujui syarat berikut. Kalau tidak setuju, mohon tidak menggunakan layanan ini. Cara kami mengelola data dijelaskan di <a href="/kebijakan-privasi">Kebijakan Privasi</a>.</p>

        <h2>1. Tentang layanan</h2>
        <p>Hadist Apa adalah situs untuk mempelajari hadist dan Al-Qur'an: pencarian hadist dengan bantuan AI, murottal Al-Qur'an, serta jadwal sholat dan cuaca. Layanan ini gratis dan dikelola secara pribadi oleh pengelola Hadist Apa.</p>

        <h2>2. Konten keagamaan</h2>
        <ul>
            <li><strong>Teks hadist</strong> beserta terjemahan dan penilaian derajatnya berasal dari kumpulan data yang tercantum di halaman <a href="/sumber">Sumber</a>. Derajat yang tampil adalah penilaian ulama yang tercatat di sumber tersebut, bukan penilaian kami sendiri.</li>
            <li><strong>Ringkasan AI</strong> hanya membantu melihat garis besar. Ringkasan bisa keliru atau berbeda dengan isi hadistnya, dan <strong>bukan fatwa</strong>. Yang menjadi patokan adalah teks hadist itu sendiri; untuk urusan hukum, rujuklah ulama.</li>
            <li><strong>Jadwal sholat</strong> dihitung otomatis mengikuti parameter Kemenag RI dan bisa berbeda satu sampai dua menit dari jadwal resmi. Ikuti jadwal masjid atau pengumuman resmi di daerahmu bila berbeda.</li>
            <li>Terjemahan dan data bisa mengandung kesalahan. Kalau menemukannya, mohon <a href="/kontak">laporkan</a> agar bisa kami perbaiki.</li>
        </ul>

        <h2>3. Akun</h2>
        <ul>
            <li>Isi data akun dengan benar dan jaga kerahasiaan password-mu. Aktivitas di akunmu menjadi tanggung jawabmu.</li>
            <li>Kalau kamu berusia di bawah 17 tahun, gunakan akun dengan sepengetahuan orang tua atau wali.</li>
            <li>Kami dapat menangguhkan atau menutup akun yang melanggar ketentuan ini.</li>
        </ul>

        <h2>4. Penggunaan yang tidak diperbolehkan</h2>
        <ul>
            <li>Mengambil data secara massal dengan bot atau skrip, atau membebani pencarian AI secara berlebihan.</li>
            <li>Mencoba membobol, mengganggu, atau mengakses bagian situs yang bukan hakmu.</li>
            <li>Mengirim spam, konten terlarang, atau data pribadi orang lain lewat formulir kontak.</li>
            <li>Menyajikan ulang konten situs ini dengan cara yang menyesatkan, misalnya memotong hadist hingga mengubah maknanya.</li>
        </ul>

